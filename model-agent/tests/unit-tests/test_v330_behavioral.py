"""v3.3.0 — "godfather curriculum" lessons: lossless parse (L3), ground-truth
physical auditor (L2), closed loop (L5), column-level canonical reconcile (L4),
and the SelfAuditor I6 ground-truth invariant (L6).

These tests exercise the two cleanly-isolatable new units end-to-end:

  * _v330_recover_dropped_priorities (L3): every PRIORITY marker in the source
    must survive parsing. Strict _V251_PRIORITY_LINE_RE drops markers with
    spaced/multi-word targets, alt separators, or missing bold. This recovers
    them as best-effort VREQ dicts so a user directive is NEVER lost.

  * SelfAuditor._i6_ground_truth (L6): turns the physical-catalog scorecard
    (produced by the L2 auditor) into a CRITICAL/HIGH/OK/WARN finding so the
    real (physical) adherence gap drives the next cycle even when the in-memory
    verifier reported green.

L2/L4/L5 are physical-catalog paths (need Spark + information_schema), so they
are covered here by static-contract assertions on the deployed source; their
behavior is proven by the live verification run.
"""
import json
import os
import re
import textwrap
import logging

import pytest

NB = os.path.join(os.path.dirname(__file__), "..", "..", "agent", "dbx_vibe_modelling_agent.ipynb")


def _load_src():
    nb = json.load(open(NB))
    return "".join("".join(c.get("source", [])) for c in nb["cells"] if c.get("cell_type") == "code")


def _slice(src, start, end):
    i = src.index(start)
    j = src.index(end, i + len(start))
    return src[i:j]


def _build_l3():
    """Extract the module-level _v330_recover_dropped_priorities verbatim."""
    src = _load_src()
    fn = _slice(src, "def _v330_recover_dropped_priorities(vibe_text, parsed):",
                "\ndef _v251_priority_to_vreq")
    ns = {"re": re}
    exec(fn, ns, ns)
    return ns["_v330_recover_dropped_priorities"]


def _build_i6():
    """Extract _i6_ground_truth and run it inside a minimal collector class."""
    src = _load_src()
    method = _slice(src, "    def _i6_ground_truth(self, scorecard):",
                    "    def _i1_vibe_capture")
    method = textwrap.dedent(method)
    cls = (
        "class _A:\n"
        "  def __init__(s):\n"
        "    s.findings=[]\n"
        "  def _emit(s, alias, inv, sev, summary, evidence=None):\n"
        "    s.findings.append({'alias':alias,'invariant':inv,'severity':sev,'summary':summary,'evidence':evidence or {}})\n"
    )
    cls += textwrap.indent(method, "  ")
    ns = {}
    exec(cls, ns, ns)
    return ns["_A"]()


# ---------------- static contracts ----------------

def test_version_is_330():
    m = re.search(r'__AGENT_VERSION__ = "(\d+)\.(\d+)\.(\d+)"', _load_src())
    assert m is not None
    assert tuple(int(x) for x in m.groups()) >= (3, 3, 0)


def test_curriculum_aliases_present():
    src = _load_src()
    for alias in (
        "priority-lossless-recover",        # L3
        "ground-truth-audit",               # L2
        "ground-truth-audit-requeue",       # L5
        "canonical-reconcile",              # L4
        "canonical-reconcile-requeue",      # L4
        "audit-i6-ground-truth",            # L6
    ):
        assert alias in src, f"missing alias {alias}"


def test_i6_wired_into_audit_and_invariant_list():
    src = _load_src()
