def _get_model_fields(model_cls) -> set[str]:
    """Extract field names from a Pydantic or SQLModel class."""
    if hasattr(model_cls, "model_fields"):
        return set(model_cls.model_fields.keys())
    return set()


def _db_api_fields(db_cls, relationship_names: set) -> set[str]:
    """Get DB model fields minus auto-generated and relationship fields."""
    all_fields = _get_model_fields(db_cls)
    return all_fields - AUTO_FIELDS - relationship_names


