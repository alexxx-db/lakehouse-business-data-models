# ---------------- L3 behavioral ----------------

def test_l3_recovers_marker_dropped_by_strict_parser():
    """A PRIORITY line with a spaced multi-word target + en-dash that the strict
    parser missed (absent from `parsed`) must be recovered."""
    recover = _build_l3()
    vibe = (
        "**PRIORITY 1 - rename_attribute: hr.job.code** - clean prefix\n"
        "PRIORITY 2 — add descriptive label to the generic FK column on project asset impact\n"
    )
    parsed = [{"priority_id": 1}]  # strict parser only caught #1
    rec = recover(vibe, parsed)
    pids = {r["priority_id"] for r in rec}
    assert 2 in pids, rec
    assert 1 not in pids, "must not duplicate an already-parsed priority"


def test_l3_does_not_duplicate_already_parsed():
    recover = _build_l3()
    vibe = "**PRIORITY 5 - remove_fk: a.b.c** - reason\n"
    parsed = [{"priority_id": 5}]
    assert recover(vibe, parsed) == []


def test_l3_flags_autogenerated_section_as_non_user():
    recover = _build_l3()
    vibe = (
        "PRIORITY 1 — keep customer domain\n"
        "=== AUTO-GENERATED NEXT_VIBES ===\n"
        "PRIORITY 9 — internal self-audit follow-up\n"
    )
    rec = {r["priority_id"]: r for r in recover(vibe, [])}
    assert rec[1]["is_user_directive"] is True
    assert rec[9]["is_user_directive"] is False


def test_l3_every_recovered_marker_has_vreq_id_and_target_or_reason():
    recover = _build_l3()
    vibe = "PRIORITY 3 — ensure every table carries a source_table tag\n"
    rec = recover(vibe, [])
    assert len(rec) == 1
    r = rec[0]
    assert r["vreq_id"] == "P003"
    assert (r["target"] or r["reason"]), "recovered VREQ must carry target or reason"


# ---------------- L6 behavioral ----------------

def test_i6_low_physical_adherence_is_critical():
    a = _build_i6()
    a._i6_ground_truth({"scored": 46, "fulfilled": 20, "failed": 24, "partial": 2, "pct": 43.5})
    f = a.findings[-1]
    assert f["invariant"] == "I6"
    assert f["severity"] == "CRITICAL", f


def test_i6_borderline_is_high_not_ok():
    a = _build_i6()
    a._i6_ground_truth({"scored": 100, "fulfilled": 85, "failed": 15, "partial": 0, "pct": 85.0})
    assert a.findings[-1]["severity"] == "HIGH", a.findings[-1]


def test_i6_meets_target_is_ok():
    a = _build_i6()
    a._i6_ground_truth({"scored": 100, "fulfilled": 95, "failed": 5, "partial": 0, "pct": 95.0})
    assert a.findings[-1]["severity"] == "OK", a.findings[-1]


def test_i6_no_scorecard_is_warn_not_silent():
    a = _build_i6()
    a._i6_ground_truth(None)
    assert a.findings[-1]["severity"] == "WARN", a.findings[-1]
    a2 = _build_i6()
    a2._i6_ground_truth({})  # ran but 0 physical columns -> scored falsey
    assert a2.findings[-1]["severity"] == "WARN", a2.findings[-1]
