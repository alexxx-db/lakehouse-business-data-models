class ProgressWriter:
    def __init__(self, path: Path):
        self.path = Path(path)

    def write(self, stage: str, *, attempt: int = 0, rate_limited: bool = False,
              resume_at: float | None = None, last_message: str = "") -> None:
        payload = {"stage": stage, "attempt": attempt, "rate_limited": rate_limited,
                   "resume_at": resume_at, "last_message": (last_message or "")[:300],
                   "updated_at": time.time()}
        tmp = self.path.with_suffix(".json.tmp")
        tmp.write_text(json.dumps(payload))
        os.replace(tmp, self.path)


def last_agent_message(events: list[dict]) -> str:
    for e in reversed(events):
        item = e.get("item") or {}
        if e.get("type") == "item.completed" and item.get("type") == "agent_message":
            return (item.get("text") or "")[:300]
    return ""


def classify_attempt(events: list[dict]) -> dict:
    errs = [e.get("message") or (e.get("error") or {}).get("message") or ""
            for e in events if e.get("type") in ("error", "turn.failed")]
    return {
        "thread_id": next((e.get("thread_id") for e in events if e.get("type") == "thread.started"), None),
        "completed": any(e.get("type") == "turn.completed" for e in events),
        "errors": errs,
        "rate_limited": bool(errs) and all(any(m in x for m in RATE_LIMIT_MARKERS) for x in errs),
    }


def validate_assessment(doc: dict, schema: dict) -> list[str]:
    import jsonschema

    v = jsonschema.Draft202012Validator(schema)
    return [f"{'/'.join(map(str, e.path)) or '<root>'}: {e.message}" for e in v.iter_errors(doc)][:50]


def _q(ident: str) -> str:
    return "`" + ident.replace("`", "``") + "`"


def _lit(value: str) -> str:
    return value.replace("'", "''")


def redact(text: str, secrets: list[str]) -> str:
    """Replace every occurrence of each non-empty secret with [REDACTED]."""
    for s in secrets:
        if s:
            text = text.replace(s, "[REDACTED]")
    return text


def preflight_statements(cfg: dict) -> list[tuple[str, str]]:
    vc = _q(cfg["vibe_catalog"])
    mm = f'{vc}.{_q(cfg["metamodel_schema"])}'
    pre = cfg.get("metamodel_prefix", "")
    out = [("warehouse", "SELECT 1"),
           ("metamodel", f"SELECT COUNT(*) AS n FROM {mm}.{_q(pre + 'domain')}"),
           ("physical", f"SELECT COUNT(*) AS n FROM {vc}.information_schema.tables "
                        f"WHERE table_schema = '{_lit(cfg['physical_schema'])}'")]
    for name, fqn in cfg["bronze_sources"].items():
        cat, sch = fqn.split(".", 1)
        out.append((f"bronze:{name}", f"SELECT COUNT(*) AS n FROM {_q(cat)}.information_schema.tables "
                                      f"WHERE table_schema = '{_lit(sch)}'"))
    return out


def metamodel_columns_statement(cfg: dict, table: str) -> str:
    """Column names of a metamodel table (lowercased); builds differ, so the version check introspects them."""
    pre = cfg.get("metamodel_prefix", "")
    return (f"SELECT lower(column_name) AS column_name FROM {_q(cfg['vibe_catalog'])}.information_schema.columns "
            f"WHERE table_schema = '{_lit(cfg['metamodel_schema'])}' AND lower(table_name) = '{_lit((pre + table).lower())}'")


def version_check_values(cfg: dict) -> tuple[str, str, str]:
    """(business, scope, version) as the agent stores them: sanitized business, short scope, bare integer version, lowercased."""
    biz = str(cfg.get("metamodel_business") or cfg.get("customer") or "").lower()
    scope = str(cfg.get("model_scope") or "").lower()
    return biz, scope, str(cfg["model_version"]).lstrip("vV")


def version_check_statement(cfg: dict, product_cols: set[str], domain_cols: set[str]) -> str | None:
    """Counts products of this domain at the pinned model version, shaped to the columns the build actually has.

    Returns None when the build exposes no version column or no way to match the domain (caller skips the check).
    """
    mm = f'{_q(cfg["vibe_catalog"])}.{_q(cfg["metamodel_schema"])}'
    pre = cfg.get("metamodel_prefix", "")
    vcol = next((c for c in ("version", "model_version") if c in product_cols), None)
    if vcol is None:
        return None
    join = ""
    if "domain" in product_cols:
        where = [f"p.domain = '{_lit(cfg['domain'])}'"]
    elif "domain_id" in product_cols:
        dcol = next((c for c in ("name", "domain") if c in domain_cols), None)
        if dcol is None:
            return None
        join = f" JOIN {mm}.{_q(pre + 'domain')} d ON p.domain_id = d.domain_id"
        where = [f"d.{dcol} = '{_lit(cfg['domain'])}'"]
    else:
        return None
    biz, scope, ver = version_check_values(cfg)
    if "business" in product_cols and biz:
        where.append(f"LOWER(p.business) = '{_lit(biz)}'")
    if "model_scope" in product_cols and scope:
        where.append(f"LOWER(p.model_scope) = '{_lit(scope)}'")
    where.append(f"CAST(p.{vcol} AS STRING) = '{_lit(ver)}'")
    return f"SELECT COUNT(*) AS n FROM {mm}.{_q(pre + 'product')} p{join} WHERE " + " AND ".join(where)


def version_check_plan(cfg: dict, product_cols: set[str], domain_cols: set[str]) -> tuple[str, str]:
    """Decide the version pre-flight: ("run", sql) | ("skip", reason) | ("fail", reason).

    Empty column sets mean the reader cannot see the table in information_schema (no grant / wrong prefix),
    which must fail; skipping is only for visible tables that genuinely lack a version or domain column.
    """
    loc = f'{cfg["vibe_catalog"]}.{cfg["metamodel_schema"]}.{cfg.get("metamodel_prefix", "")}'
    hint = "not visible to the reader — grant SELECT on the model catalog"
    if not product_cols:
        return "fail", f"metamodel table {loc}product {hint}"
    if not any(c in product_cols for c in ("version", "model_version")):
        return "skip", "skipped: metamodel has no version column"
    if "domain" not in product_cols:
        if "domain_id" not in product_cols:
            return "skip", "skipped: metamodel product has no domain column"
        if not domain_cols:
            return "fail", f"metamodel table {loc}domain {hint}"
        if not any(c in domain_cols for c in ("name", "domain")):
            return "skip", "skipped: metamodel domain table has no name column"
    sql = version_check_statement(cfg, product_cols, domain_cols)
    return ("run", sql) if sql else ("skip", "skipped: metamodel has no usable version/domain columns")


SKILL_VERSION_FILE = ".vibe-skill-version"  # "<skills_version> <skills_ref>", stamped on every bundled skill


def stage_bundled_skills(src: Path, dst: Path, names: list[str]) -> dict:
    """Copy each named skill from the bundled tree into ``dst``; ``summary.json.skills`` for the run.

    Skills come only from the bundle shipped with the job, so the run uses exactly the
    release's pinned snapshot. Each staged skill must carry its SKILL.md and version
    marker; ``markers`` records what was staged, and ``version``/``ref`` are filled when
    every marker agrees (``commit`` is the short sha of a ``dev:<branch>@<sha>`` ref, and empty for a
    ``dev:`` ref without one).
    """
    src, dst = Path(src), Path(dst)
    markers = {}
    for name in names:
        skill = src / name
        marker = skill / SKILL_VERSION_FILE
        if not (skill / "SKILL.md").is_file() or not marker.is_file():
            raise RuntimeError(f"bundled skill {name} is incomplete in {src} (needs SKILL.md and {SKILL_VERSION_FILE})")
        shutil.copytree(skill, dst / name)
        markers[name] = marker.read_text().strip()
    agreed = set(markers.values())
    version, _, ref = (agreed.pop() if len(agreed) == 1 else "").partition(" ")
    commit = (ref.rpartition("@")[2] if "@" in ref else "") if ref.startswith("dev:") else ref
    return {"source": "bundle", "path": str(src), "markers": markers,
            "version": version or None, "ref": ref or None, "commit": commit or None}
