class TestRunArtifactOutRunIdOptional:
    """Lock the v_0_5_0 widening of ``RunArtifactOut.run_id`` to ``Optional[str]``.

    Imported ModelVersions write RunArtifact rows with ``run_id=NULL``
    (imports are syncs, not runs). Before the widen, the
    ``/api/model-versions/{id}/artifacts`` endpoint returned HTTP 500 with
    a Pydantic ``response[*].run_id: Input should be a valid string``
    error whenever any artifact in the response had a null run_id. The
    flow-level coverage lives in
    ``test_artifact_content.py::TestArtifactListByVersionWithNullRunId``;
    this contract test pins the type annotation so a future model edit
    that re-narrows the field is caught at the layer of the schema, not
    only at the endpoint.
    """

    def test_run_id_annotation_accepts_none(self):
        from typing import Union, get_args, get_origin

        field = api.RunArtifactOut.model_fields["run_id"]
        ann = field.annotation
        # ``Optional[str]`` is ``Union[str, None]`` — accept either spelling.
        if get_origin(ann) is Union:
            assert type(None) in get_args(ann), (
                f"RunArtifactOut.run_id must accept None; got annotation {ann!r}."
            )
        else:
            raise AssertionError(
                f"RunArtifactOut.run_id must be Optional[str] (Union[str, None]); "
                f"got non-Union annotation {ann!r}."
            )

    def test_run_id_default_is_none(self):
        """Default must be ``None`` so callers constructing an instance
        from an import row (run_id absent) don't have to pass it explicitly."""
        field = api.RunArtifactOut.model_fields["run_id"]
        assert field.default is None, (
            f"RunArtifactOut.run_id default must be None; got {field.default!r}."
        )

    def test_instance_with_null_run_id_validates(self):
        """End-to-end: an import-shaped row (run_id=None) must validate
        cleanly. Pre-widen, this raised ValidationError; the test would
        go red and surface the regression directly at the Pydantic layer
        rather than via a 500 in the artifacts endpoint."""
