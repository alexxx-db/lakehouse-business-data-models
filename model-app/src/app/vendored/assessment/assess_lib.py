from pathlib import Path
from typing import Callable

RATE_LIMIT_MARKERS = ("429", "REQUEST_LIMIT_EXCEEDED", "rate limit")


def load_config(path: str) -> dict:
    return json.loads(Path(path).read_text())


# platform.machine() -> the arch names each pinned CLI's release assets use.
GENIE_ARCH = {"x86_64": "x86_64", "aarch64": "aarch64", "arm64": "aarch64"}
DATABRICKS_CLI_ARCH = {"x86_64": "amd64", "aarch64": "arm64", "arm64": "arm64"}

# Release-asset layout of each pinned CLI on GitHub.
GITHUB = "https://github.com"
CLI_REPOS = {"genie": "databricks/genie-code-cli", "databricks_cli": "databricks/cli"}


def cli_asset(tool: str, tag: str, arch: str) -> str:
    """Release asset name of a pinned CLI for one of its arch names (GENIE_ARCH / DATABRICKS_CLI_ARCH values)."""
    if tool == "genie":
        return f"genie-package-{arch}-unknown-linux-musl.tar.gz"
    return f"databricks_cli_{tag.lstrip('v')}_linux_{arch}.zip"


def release_url(tool: str, tag: str, asset: str, github: str = GITHUB) -> str:
    return f"{github}/{CLI_REPOS[tool]}/releases/download/{tag}/{asset}"


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def tool_downloads(cfg: dict, machine: str) -> dict[str, dict]:
    """Per pinned CLI (``genie``, ``databricks_cli``): ``tag``, ``sha256``, ``asset`` and ``url``
    for this machine, from the pins ``config.json`` carries (VERSIONS.json at launch)."""
    genie_arch = GENIE_ARCH[machine]
    cli_arch = DATABRICKS_CLI_ARCH[machine]
    out = {}
    for tool, arch in (("genie", genie_arch), ("databricks_cli", cli_arch)):
        pin = cfg[tool]
        asset = cli_asset(tool, pin["tag"], arch)
        out[tool] = {"tag": pin["tag"], "sha256": pin["sha256"][arch], "asset": asset,
                     "url": release_url(tool, pin["tag"], asset)}
    return out


def ensure_pinned_archive(cache_dir: Path, download: dict, fetch: Callable[[str, Path], Path]) -> Path:
    """The pinned archive in its tag-keyed cache folder, verified against the pin.

    A cached archive is re-hashed before reuse; a missing or mismatched one is
    (re)downloaded and must then match, or this raises. ``cache_dir`` is
    ``<tools>/<tool>/<tag>``, so a pin change never reuses another tag's files.
    """
    archive = cache_dir / download["asset"]
    if archive.is_file() and sha256_file(archive) == download["sha256"]:
        return archive
    shutil.rmtree(cache_dir, ignore_errors=True)
    cache_dir.mkdir(parents=True, exist_ok=True)
    fetch(download["url"], archive)
    actual = sha256_file(archive)
    if actual != download["sha256"]:
        archive.unlink(missing_ok=True)
        raise RuntimeError(f"{download['asset']} sha256 mismatch: {actual} != pinned {download['sha256']}")
    return archive


